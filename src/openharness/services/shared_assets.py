# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

@dataclass
class SharedAssetManifest:
    """Manifest of all pre-generated shared assets for a project."""

    project_id: str
    created_at: float
    assets: list[SharedAsset] = field(default_factory=list)
    brand_config_hash: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "project_id": self.project_id,
            "created_at": self.created_at,
            "assets": [
                {
                    "name": a.name,
                    "file_path": a.file_path,
                    "asset_type": a.asset_type,
                    "description": a.description,
                    "content_hash": a.content_hash,
                }
                for a in self.assets
            ],
            "brand_config_hash": self.brand_config_hash,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "SharedAssetManifest":
        assets = [
            SharedAsset(
                name=a["name"],
                file_path=a["file_path"],
                asset_type=a["asset_type"],
                description=a.get("description", ""),
                content_hash=a.get("content_hash", ""),
            )
            for a in data.get("assets", [])
        ]
        return cls(
            project_id=data.get("project_id", ""),
            created_at=data.get("created_at", 0.0),
            assets=assets,
            brand_config_hash=data.get("brand_config_hash", ""),
        )

    @classmethod
    def from_json(cls, json_str: str) -> "SharedAssetManifest":
        return cls.from_dict(json.loads(json_str))


# ---------------------------------------------------------------------------
# Pre-generation logic
# ---------------------------------------------------------------------------

def detect_needed_assets(scene_descriptions: list[str]) -> list[str]:
    """Determine which shared assets a project needs based on scene descriptions.

    Scans descriptions for keywords that indicate each asset type is needed.
    Returns a list of asset names (e.g. ["color_palette", "font_loader"]).
    """
    needed: set[str] = set()
    # Color palette is always needed (every scene uses colors).
    needed.add("color_palette")
    combined = " ".join(scene_descriptions).lower()
    if any(kw in combined for kw in ["text", "title", "caption", "subtitle", "typography"]):
        needed.add("font_loader")
        needed.add("easing")  # text usually animates in
    if any(kw in combined for kw in ["background", "backdrop", "gradient", "sky"]):
        needed.add("background")
    if any(kw in combined for kw in ["logo", "brand", "channel", "intro"]):
        needed.add("logo")
    if any(kw in combined for kw in ["animat", "transition", "motion", "slide", "fade"]):
        needed.add("easing")
    return sorted(needed)


def load_manifest(project_root: str | Path) -> SharedAssetManifest | None:
    """Load the shared-asset manifest for a project, or None if not yet created."""
    manifest_path = Path(project_root) / "shared" / "manifest.json"
    if not manifest_path.is_file():
        return None
    try:
        return SharedAssetManifest.from_json(manifest_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        log.warning("failed to load shared-asset manifest: %s", exc)
        return None


def save_manifest(project_root: str | Path, manifest: SharedAssetManifest) -> None:
    """Save the manifest to ``shared/manifest.json``."""
    shared_dir = Path(project_root) / "shared"
    shared_dir.mkdir(parents=True, exist_ok=True)
    (shared_dir / "manifest.json").write_text(manifest.to_json(), encoding="utf-8")


def generate_shared_assets(
    project_root: str | Path,
    *,
    project_id: str,
    brand_config: dict[str, Any] | None = None,
    scene_descriptions: list[str] | None = None,
    force: bool = False,
) -> SharedAssetManifest:
    """Generate all needed shared assets for a project.

    Args:
        project_root: Project root directory. Assets go in ``shared/``.
        project_id: Project identifier for the manifest.
        brand_config: Optional brand config dict (colors, fonts, etc.).
        scene_descriptions: Optional list of scene descriptions to
            detect which assets are needed.
        force: If True, regenerate even if the manifest exists and the
            brand config hasn't changed.

    Returns:
        The manifest of generated assets.
    """
    project_root = Path(project_root)
    shared_dir = project_root / "shared"
    brand_config = brand_config or {}
    brand_hash = _hash_brand_config(brand_config)

    # Check if we can skip regeneration
    existing = load_manifest(project_root)
    if existing and not force and existing.brand_config_hash == brand_hash:
        # Brand config unchanged — assets are still valid.
        # But check if files still exist.
        all_exist = all((project_root / a.file_path).is_file() for a in existing.assets)
        if all_exist:
            log.debug("shared assets already up-to-date for %s", project_id)
            return existing

    # Determine which assets are needed
    needed = (
        detect_needed_assets(scene_descriptions)
        if scene_descriptions
        else [a["name"] for a in DEFAULT_SHARED_ASSETS]
    )

    shared_dir.mkdir(parents=True, exist_ok=True)

    assets: list[SharedAsset] = []
    for asset_def in DEFAULT_SHARED_ASSETS:
        if asset_def["name"] not in needed:
            continue
        content = _render_template(asset_def["template"], brand_config)
        file_path = shared_dir / Path(asset_def["file_path"]).name
        file_path.parent.mkdir(parents=True, exist_ok=True)
        file_path.write_text(content, encoding="utf-8")
        content_hash = hashlib.sha1(content.encode("utf-8")).hexdigest()
        assets.append(
            SharedAsset(
                name=asset_def["name"],
                file_path=str(file_path.relative_to(project_root)),
                asset_type=asset_def["asset_type"],
                description=asset_def["description"],
                content_hash=content_hash,
            )
        )

    manifest = SharedAssetManifest(
        project_id=project_id,
        created_at=time.time(),
        assets=assets,
        brand_config_hash=brand_hash,
    )
    save_manifest(project_root, manifest)
    return manifest


def _hash_brand_config(brand_config: dict[str, Any]) -> str:
    """Hash the brand config so we can detect changes."""
    if not brand_config:
        return ""
    payload = json.dumps(brand_config, sort_keys=True, default=str)
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()


def _render_template(template: str, brand_config: dict[str, Any]) -> str:
    """Render a template by substituting brand config values."""
    colors = brand_config.get("colors", {})
    brand_colors = {
        "primary": colors.get("primary", "#1A1A2E"),
        "secondary": colors.get("secondary", "#16213E"),
        "accent": colors.get("accent", "#E94560"),
    }
    fonts = brand_config.get("fonts", {})
    result = template
    result = result.replace("{{BRAND_COLORS}}", json.dumps(brand_colors, indent=2))
    result = result.replace("{{DERIVED_COLORS}}", json.dumps(brand_colors, indent=2))
    result = result.replace("{{HEADING_FONT}}", fonts.get("heading", "Inter"))
    result = result.replace("{{BODY_FONT}}", fonts.get("body", "Inter"))
    result = result.replace("{{BRAND_EASING}}", brand_config.get("easing", "cubic-bezier(0.4, 0.0, 0.2, 1)"))
    result = result.replace("{{SAFE_AREA}}", str(brand_config.get("safe_area", 220)))
    return result


def is_asset_up_to_date(
    project_root: str | Path,
    asset_name: str,
    *,
    brand_config: dict[str, Any] | None = None,
) -> bool:
    """Check if a specific shared asset exists and is up-to-date.

    Returns True if the asset file exists AND the brand config hash
    matches the manifest. Returns False if the asset needs regeneration.
    """
    manifest = load_manifest(project_root)
    if manifest is None:
        return False
    brand_hash = _hash_brand_config(brand_config or {})
    if manifest.brand_config_hash != brand_hash:
        return False
    for asset in manifest.assets:
        if asset.name == asset_name:
            return (Path(project_root) / asset.file_path).is_file()
    return False
